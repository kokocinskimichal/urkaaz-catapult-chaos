package com.urkaaaz.contracts

/** Shared timing for the Ancient War Oak unit-attack animation and damage impact. */
object BossAttackAnimationTiming {
    const val ANCIENT_WAR_OAK_UNIT_ATTACK_FRAME_COUNT = 60
    const val ANCIENT_WAR_OAK_UNIT_ATTACK_DURATION_MILLISECONDS = 4_042L
    const val ANCIENT_WAR_OAK_UNIT_ATTACK_IMPACT_FRAME_INDEX = 34
    const val ANCIENT_WAR_OAK_UNIT_ATTACK_WINDUP_MILLISECONDS =
        ANCIENT_WAR_OAK_UNIT_ATTACK_DURATION_MILLISECONDS *
            ANCIENT_WAR_OAK_UNIT_ATTACK_IMPACT_FRAME_INDEX /
            ANCIENT_WAR_OAK_UNIT_ATTACK_FRAME_COUNT + 1L
    const val ANCIENT_WAR_OAK_UNIT_ATTACK_WINDUP_SECONDS =
        ANCIENT_WAR_OAK_UNIT_ATTACK_WINDUP_MILLISECONDS / 1_000f
}
